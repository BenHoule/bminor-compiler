int equal(int a, int b) {
  return a == b;
}

int not_equal(int a, int b) {
  return a != b;
}

int signed_less(int a, int b) {
  return a < b;
}

int unsigned_less(unsigned int a, unsigned int b) {
  return a < b;
}

int signed_less_equal(int a, int b) {
  return a <= b;
}

int signed_greater(int a, int b) {
  return a > b;
}

int signed_greater_equal(int a, int b) {
  return a >= b;
}
