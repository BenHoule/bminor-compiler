double float_add(double a, double b) {
  return a + b;
}

double float_subtract(double a, double b) {
  return a - b;
}

double float_multiply(double a, double b) {
  return a * b;
}

double float_divide(double a, double b) {
  return a / b;
}

int float_less(double a, double b) {
  return a < b;
}

int float_equal(double a, double b) {
  return a == b;
}
