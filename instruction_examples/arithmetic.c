int add(int a, int b) {
  return a + b;
}

int subtract(int a, int b) {
  return a - b;
}

int multiply(int a, int b) {
  return a * b;
}

int signed_divide(int a, int b) {
  return a / b;
}

int signed_remainder(int a, int b) {
  return a % b;
}

unsigned int unsigned_divide(unsigned int a, unsigned int b) {
  return a / b;
}

unsigned int unsigned_remainder(unsigned int a, unsigned int b) {
  return a % b;
}

int negate(int value) {
  return -value;
}
